    // Se obtiene la lista
    /*******************************************************************/
    private function getDataList($filter, $params = [], $limit = null){

        /************************************/
        // Se genera la query
        $query = [
            'data'    => '
                usuarios_listado.idUsuario,
                usuarios_listado.email,
                usuarios_listado.Nombre,
                usuarios_listado.Ultimo_acceso,
                core_estados.Nombre AS Estado,
                core_estados.Color AS EstadoColor',
            'table'   => 'usuarios_listado',
            'join'    => 'LEFT JOIN core_estados ON core_estados.idEstado = usuarios_listado.idEstado',
            'where'   => $filter,
            'params'  => $params,
            'group'   => '',
            'having'  => '',
            'order'   => 'usuarios_listado.email ASC, usuarios_listado.idUsuario ASC',
            'limit'   => ($limit ?? ConfigAPP::APP["N_MaxItems"])
        ];
        // Preparo los datos
        $xParams = ['query' => $query];
        //Se retornan los datos
        return $this->Base_GetList($xParams);
    }

